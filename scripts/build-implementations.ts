import type { Plugin } from 'esbuild';

import { wrapCliTask } from '@mnaoumov/typescript-dev-toolkit/cli-utils';
import builtinModules from 'builtin-modules';
import { context } from 'esbuild';
import { existsSync } from 'node:fs';
import { join } from 'node:path/posix';
import { exit } from 'node:process';

async function build(format: 'cjs' | 'esm'): Promise<void> {
  const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
*/
`;

  const buildContext = await context({
    banner: {
      js: banner
    },
    bundle: true,
    entryPoints: ['src/obsidian/implementations/index.ts'],
    external: [
      'obsidian',
      'electron',
      '@codemirror/autocomplete',
      '@codemirror/collab',
      '@codemirror/commands',
      '@codemirror/language',
      '@codemirror/lint',
      '@codemirror/search',
      '@codemirror/state',
      '@codemirror/view',
      '@lezer/common',
      '@lezer/highlight',
      '@lezer/lr',
      ...builtinModules
    ],
    format,
    logLevel: 'info',
    outfile: `dist/${format}/implementations.${format === 'cjs' ? 'cjs' : 'mjs'}`,
    plugins: [
      typescriptResolutionPlugin()
    ],
    sourcemap: 'inline',
    target: 'ES2022',
    treeShaking: true
  });

  await buildContext.rebuild();
}

async function main(): Promise<void> {
  await build('cjs');
  await build('esm');
  exit(0);
}

function typescriptResolutionPlugin(): Plugin {
  return {
    name: 'typescript-resolution',
    setup(pluginBuild): void {
      pluginBuild.onResolve({ filter: /\.js$/ }, (resolveOptions) => {
        const extensions = ['.ts', '.d.ts'];
        for (const extension of extensions) {
          const fullPath = join(resolveOptions.resolveDir.replaceAll('\\', '/'), `${resolveOptions.path.slice(0, -'.js'.length)}${extension}`);
          if (existsSync(fullPath)) {
            return { path: fullPath };
          }
        }
        return null;
      });
    }
  };
}

await wrapCliTask(main);
