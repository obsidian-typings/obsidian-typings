import { wrapCliTask } from '@mnaoumov/typescript-dev-toolkit/cli-utils';
import {
  appendFile,
  readdir,
  writeFile
} from 'node:fs/promises';
import {
  basename,
  extname,
  join
} from 'node:path/posix';

function generateExportLine(file: string): string {
  const exportPrefix = file.endsWith('.d.ts') ? 'export type' : 'export';
  return `${exportPrefix} * from './${file}';`;
}

async function generateIndex(directory: string, extension: string): Promise<void> {
  const entries = await readdir(directory, { recursive: true });
  const files = entries
    .map((file) => file.replaceAll('\\', '/'))
    .filter((file) => {
      const fileExtension = getExtension(file);
      return ['.d.ts', '.ts'].includes(fileExtension)
        && basename(file, fileExtension) !== 'index';
    }).sort((a, b) => a.localeCompare(b));
  const lines = files.map((file) => generateExportLine(file));
  const prefix = '/* THIS IS A GENERATED/BUNDLED FILE BY BUILD SCRIPT */\n\n';
  const indexFile = join(directory, `index${extension}`);
  await writeFile(indexFile, `${prefix + lines.join('\n')}\n`, 'utf-8');
}

function getExtension(file: string): string {
  return file.endsWith('.d.ts') ? '.d.ts' : extname(file);
}

async function main(): Promise<void> {
  await generateIndex('src', '.d.ts');
  await generateIndex('src/obsidian', '.d.ts');
  await generateIndex('src/obsidian/augmentations', '.d.ts');
  await generateIndex('src/obsidian/implementations', '.ts');
  await appendFile('src/obsidian/implementations/index.ts', 'export type * from \'../../index.d.ts\';\n', 'utf-8');
}

await wrapCliTask(main);
